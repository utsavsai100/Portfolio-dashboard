export const calculateSectorSummaries = (stocks) => {
  const sectorSummaries = {};

  stocks.forEach(stock => {
    const sector = stock.sector;

    if (!sectorSummaries[sector]) {
      sectorSummaries[sector] = {
        sector,
        totalInvestment: 0,
        totalPresentValue: 0,
        gainLoss: 0,
        gainLossPercentage: 0,
        stockCount: 0
      };
    }

    // Safety check for buyPrice and quantity
    const price = Number(stock.buyPrice) || 0;
    const qty = Number(stock.quantity) || 0;
    const investment = price * qty;
    const presentValue = (Number(stock.cmp) || 0) * qty;
    const gainLoss = presentValue - investment;

    sectorSummaries[sector].totalInvestment += investment;
    sectorSummaries[sector].totalPresentValue += presentValue;
    sectorSummaries[sector].gainLoss += gainLoss;
    sectorSummaries[sector].stockCount += 1;
  });

  Object.values(sectorSummaries).forEach(sector => {
    if (sector.totalInvestment > 0) {
      sector.gainLossPercentage = (sector.gainLoss / sector.totalInvestment) * 100;
    }
  });

  return Object.values(sectorSummaries);
};